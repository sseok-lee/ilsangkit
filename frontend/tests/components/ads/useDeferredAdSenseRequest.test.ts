import { afterEach, describe, expect, it } from 'vitest'
import { mountRequestHarness } from '../../helpers/adHarness'
let h: Awaited<ReturnType<typeof mountRequestHarness>> | undefined
afterEach(() => {
  h?.dispose()
  h = undefined
})
describe('manual slot requests', () => {
  it('waits for ready and positive width, then requests the element once', async () => {
    h = await mountRequestHarness({ width: 0, ready: false })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setReady(true)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setWidth(353)
    h.triggerResize()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.request.attempted.value).toBe(true)
    expect(h.request.outcome.value).toBe('returned')
    h.triggerResize()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('requires policy, connected DOM and a visible ins', async () => {
    h = await mountRequestHarness({ allowed: false })
    await h.flush()
    h.element.value!.style.display = 'none'
    h.setAllowed(true)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.element.value!.style.display = 'block'
    h.host.remove()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    document.body.appendChild(h.host)
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it.each([NaN, undefined, -1])('does not request an invalid width (%s)', async (width) => {
    h = await mountRequestHarness({ width: 0 })
    h.setWidth(width as number)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
  })
  it('deduplicates wait events and handles synchronous reentry and throws', async () => {
    h = await mountRequestHarness({ ready: false })
    await h.flush()
    h.request.reevaluate()
    h.request.reevaluate()
    await h.flush()
    expect(h.events.mock.calls.filter(([kind]) => kind === 'waiting-sdk')).toHaveLength(1)
    h.push.mockImplementation(() => {
      h!.request.reevaluate()
      h!.triggerResize()
      throw new TypeError('private details')
    })
    h.setReady(true)
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.request.outcome.value).toBe('error')
    expect(h.events).toHaveBeenCalledWith('push-error', 'type-error')
    h.request.clearPendingAdRequest()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    h.replaceElement()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(2)
  })
  it('uses window resize when ResizeObserver is unavailable', async () => {
    h = await mountRequestHarness({ width: 0, resizeObserver: false })
    await h.flush()
    h.setWidth(353)
    window.dispatchEvent(new Event('resize'))
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('ignores stale observer callbacks and SDK readiness after unmount', async () => {
    h = await mountRequestHarness({ width: 0 })
    await h.flush()
    const old = h.observers[0]
    h.replaceElement()
    await h.flush()
    h.setWidth(353)
    old.callback([], {} as ResizeObserver)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.triggerResize()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    h.setReady(false)
    h.replaceElement()
    await h.flush()
    h.unmount()
    h.setReady(true)
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.observers.every((observer) => observer.elements.size === 0)).toBe(true)
  })
})
