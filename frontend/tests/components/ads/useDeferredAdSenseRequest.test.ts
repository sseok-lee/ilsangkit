import { afterEach, describe, expect, it, vi } from 'vitest'
import { mountPluginHarness, mountRequestHarness } from '../../helpers/adHarness'
import { useAdSenseRuntime } from '~/composables/useAdSenseRuntime'
let h: Awaited<ReturnType<typeof mountRequestHarness>> | undefined
afterEach(() => {
  h?.dispose()
  h = undefined
  vi.restoreAllMocks()
})
describe('manual slot requests', () => {
  it('waits for 320 content pixels, then requests once', async () => {
    h = await mountRequestHarness({ minWidth: 320, width: 319.75 })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.beforePush).not.toHaveBeenCalled()
    expect(h.events).toHaveBeenCalledWith('waiting-width')
    expect(h.request.attempted.value).toBe(false)
    expect(h.request.outcome.value).toBe('idle')
    h.request.reevaluate()
    h.triggerResize()
    await h.flush()
    expect(h.events.mock.calls.filter(([kind]) => kind === 'waiting-width')).toHaveLength(1)
    h.setWidth(320)
    h.triggerResize()
    await h.flush()
    expect(h.beforePush).toHaveBeenCalledTimes(1)
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.request.attempted.value).toBe(true)
    h.triggerResize()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.observers.every(({ elements }) => elements.size === 0)).toBe(true)
  })
  it.each([
    { width: 0, requests: 0 },
    { width: 319, requests: 0 },
    { width: 320, requests: 1 },
    { width: 353, requests: 1 },
    { width: NaN, requests: 0 },
    { width: Infinity, requests: 0 },
  ])('requires finite content width at the threshold ($width)', async ({ width, requests }) => {
    h = await mountRequestHarness({ minWidth: 320, width })
    await h.flush()
    expect(h.beforePush).toHaveBeenCalledTimes(requests)
    expect(h.push).toHaveBeenCalledTimes(requests)
    expect(h.request.attempted.value).toBe(requests === 1)
    if (!requests) {
      expect(h.events).toHaveBeenCalledWith('waiting-width')
      h.setWidth(320)
      h.triggerResize()
      await h.flush()
      expect(h.push).toHaveBeenCalledTimes(1)
    }
  })
  it('uses the parent width even when the child has 320 pixels', async () => {
    h = await mountRequestHarness({ minWidth: 320, width: 319, ready: false })
    await h.flush()
    h.setElementWidth(h.element.value!, 320)
    h.setReady(true)
    await h.flush()
    expect(h.element.value!.getBoundingClientRect().width).toBe(320)
    expect(h.push).not.toHaveBeenCalled()
    h.setElementWidth(h.container.value!, 320)
    h.triggerResize()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('subtracts both padding and borders from the parent before requesting', async () => {
    h = await mountRequestHarness({ minWidth: 320, width: 340, ready: false })
    await h.flush()
    h.container.value!.style.cssText = 'padding: 0 10px; border: 1px solid black'
    h.setReady(true)
    await h.flush()
    expect(h.beforePush).not.toHaveBeenCalled()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.events).toHaveBeenCalledWith('waiting-width')
    h.setWidth(342)
    h.triggerResize()
    await h.flush()
    expect(h.beforePush).toHaveBeenCalledTimes(1)
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('keeps the default slot offsetWidth contract at one pixel', async () => {
    h = await mountRequestHarness({ width: 1, ready: false })
    await h.flush()
    h.setElementWidth(h.container.value!, 0)
    h.container.value!.style.cssText = 'padding: 10px; border: 1px solid black'
    h.setReady(true)
    await h.flush()
    expect(h.beforePush).toHaveBeenCalledTimes(1)
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it.each(['sdk', 'proximity', 'visibility'] as const)(
    'rechecks a reduced width after waiting for %s and recovers',
    async (wait) => {
      h = await mountRequestHarness({
        minWidth: 320,
        width: 320,
        ready: wait !== 'sdk',
        near: wait !== 'proximity',
        visible: wait !== 'visibility',
      })
      await h.flush()
      expect(h.push).not.toHaveBeenCalled()
      h.setWidth(319.75)
      if (wait === 'sdk') h.setReady(true)
      if (wait === 'proximity') h.enterViewport()
      if (wait === 'visibility') h.setVisibility('visible')
      await h.flush()
      expect(h.beforePush).not.toHaveBeenCalled()
      expect(h.push).not.toHaveBeenCalled()
      expect(h.events).toHaveBeenCalledWith('waiting-width')
      expect(h.request.attempted.value).toBe(false)
      h.leaveViewport()
      h.setWidth(320)
      h.triggerResize()
      await h.flush()
      expect(h.push).toHaveBeenCalledTimes(1)
    }
  )
  it.each([undefined, 320])('rechecks width immediately before marking an attempt (minWidth %s)', async (minWidth) => {
    h = await mountRequestHarness({ minWidth, width: 320, near: false })
    await h.flush()
    const parent = h.container.value!
    const property = minWidth === undefined ? 'offsetWidth' : 'getBoundingClientRect'
    const descriptor = Object.getOwnPropertyDescriptor(parent, property)
    let reads = 0
    Object.defineProperty(parent, property, {
      configurable: true,
      ...(minWidth === undefined
        ? { get: () => reads++ === 0 ? 320 : 0 }
        : { value: () => new DOMRect(0, 0, reads++ === 0 ? 320 : 319.75, 0) }),
    })
    h.enterViewport()
    await h.flush()
    expect(h.beforePush).not.toHaveBeenCalled()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.request.attempted.value).toBe(false)
    expect(h.request.outcome.value).toBe('idle')
    expect(h.events).toHaveBeenCalledWith('waiting-width')
    expect(h.observers.some(({ elements }) => elements.has(parent))).toBe(true)
    if (descriptor) Object.defineProperty(parent, property, descriptor)
    else Reflect.deleteProperty(parent, property)
    h.triggerResize()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('recovers to minimum width with the window resize fallback and removes it', async () => {
    const remove = vi.spyOn(window, 'removeEventListener')
    h = await mountRequestHarness({ minWidth: 320, width: 319.75, resizeObserver: false })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setWidth(320)
    window.dispatchEvent(new Event('resize'))
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(remove).toHaveBeenCalledWith('resize', expect.any(Function))
    window.dispatchEvent(new Event('resize'))
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('ignores stale minimum-width callbacks after clearing, replacement, policy off and unmount', async () => {
    h = await mountRequestHarness({ minWidth: 320, width: 319.75 })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    const old = h.observers.find(({ elements }) => elements.size)!
    const retry = () => old.callback([], {} as ResizeObserver)
    h.request.clearPendingAdRequest()
    h.setWidth(320)
    retry()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setWidth(319.75)
    h.replaceElement()
    await h.flush()
    h.setWidth(320)
    retry()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setAllowed(false)
    await h.flush()
    retry()
    h.triggerResize()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setWidth(319.75)
    h.setAllowed(true)
    await h.flush()
    const latest = h.observers.find(({ elements }) => elements.size)!
    h.unmount()
    h.setWidth(320)
    retry()
    latest.callback([], {} as ResizeObserver)
    window.dispatchEvent(new Event('resize'))
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.observers.every(({ elements }) => elements.size === 0)).toBe(true)
    expect(h.intersections.every(({ elements }) => elements.size === 0)).toBe(true)
  })
  it('remembers proximity while waiting and requires it again for a new ins', async () => {
    h = await mountRequestHarness({ ready: false, near: false })
    await h.flush()
    h.enterViewport()
    await h.flush()
    h.leaveViewport()
    h.setReady(true)
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    h.replaceElement()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    h.enterViewport()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(2)
  })
  it('waits for a visible document without causing another SDK load', async () => {
    h = await mountRequestHarness({ visible: false })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.events).toHaveBeenCalledWith('waiting-visible')
    h.setVisibility('visible')
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(document.querySelectorAll('script[src*="adsbygoogle.js"]')).toHaveLength(0)
  })
  it('uses exact proximity options and accepts zero intersection ratio and height', async () => {
    h = await mountRequestHarness({ near: false })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.events).toHaveBeenCalledWith('waiting-viewport')
    const active = h.intersections.filter(({ elements }) => elements.size)
    expect(active).toHaveLength(1)
    expect(active[0].options).toEqual({
      root: null,
      rootMargin: '0px 0px 300px 0px',
      threshold: 0,
    })
    expect(active[0].elements.has(h.container.value!)).toBe(true)
    active[0].callback(
      [{ target: document.body as Element, isIntersecting: true, intersectionRatio: 0 } as IntersectionObserverEntry],
      {} as IntersectionObserver
    )
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.enterViewport()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(active[0].elements.size).toBe(0)
  })
  it('deduplicates the first blocking wait and preserves proximity through width recovery', async () => {
    h = await mountRequestHarness({ ready: false, width: 0, near: false, visible: false })
    await h.flush()
    h.request.reevaluate()
    await h.flush()
    expect(h.events.mock.calls.map(([kind]) => kind)).toEqual(['waiting-sdk'])
    h.setReady(true)
    await h.flush()
    expect(h.events.mock.calls.map(([kind]) => kind)).toEqual(['waiting-sdk', 'waiting-width'])
    h.enterViewport()
    await h.flush()
    h.leaveViewport()
    h.setWidth(353)
    h.triggerResize()
    await h.flush()
    expect(h.events.mock.calls.map(([kind]) => kind)).toEqual([
      'waiting-sdk',
      'waiting-width',
      'waiting-visible',
    ])
    h.request.reevaluate()
    h.setVisibility('hidden')
    await h.flush()
    expect(h.events.mock.calls.filter(([kind]) => kind === 'waiting-visible')).toHaveLength(1)
    h.setVisibility('visible')
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('deduplicates viewport waits until the blocking condition changes', async () => {
    h = await mountRequestHarness({ near: false, visible: false })
    await h.flush()
    h.request.reevaluate()
    h.leaveViewport()
    await h.flush()
    expect(h.events.mock.calls.map(([kind]) => kind)).toEqual(['waiting-viewport'])
    h.enterViewport()
    await h.flush()
    expect(h.events.mock.calls.map(([kind]) => kind)).toEqual([
      'waiting-viewport',
      'waiting-visible',
    ])
  })
  it('falls back only on proximity when IntersectionObserver is unavailable', async () => {
    h = await mountRequestHarness({
      intersectionObserver: false,
      near: false,
      visible: false,
      width: 0,
    })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.events).toHaveBeenCalledWith('waiting-width')
    h.setWidth(353)
    h.triggerResize()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.events).toHaveBeenCalledWith('waiting-visible')
    h.setVisibility('visible')
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('clears request observers and visibility listeners while preserving acquired proximity', async () => {
    const remove = vi.spyOn(document, 'removeEventListener')
    h = await mountRequestHarness({ visible: false, width: 0 })
    await h.flush()
    h.setWidth(353)
    h.triggerResize()
    await h.flush()
    h.request.clearPendingAdRequest()
    expect(h.observers.every(({ elements }) => elements.size === 0)).toBe(true)
    expect(h.intersections.every(({ elements }) => elements.size === 0)).toBe(true)
    expect(remove.mock.calls.some(([type]) => type === 'visibilitychange')).toBe(true)
    h.leaveViewport()
    h.request.reevaluate()
    await h.flush()
    h.setVisibility('visible')
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(remove.mock.calls.filter(([type]) => type === 'visibilitychange')).toHaveLength(2)
  })
  it('rejects stale IO across replacement, policy off, generation clearing and unmount', async () => {
    h = await mountRequestHarness({ near: false })
    await h.flush()
    const old = h.intersections.find(({ elements }) => elements.size)!
    const parent = h.container.value!
    const enter = () =>
      old.callback(
        [{ target: parent as Element, isIntersecting: true, intersectionRatio: 0 } as IntersectionObserverEntry],
        {} as IntersectionObserver
      )
    h.request.clearPendingAdRequest()
    h.request.reevaluate()
    await h.flush()
    enter()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.replaceElement()
    await h.flush()
    enter()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setAllowed(false)
    await h.flush()
    h.enterViewport()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.intersections.every(({ elements }) => elements.size === 0)).toBe(true)
    h.setAllowed(true)
    h.leaveViewport()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.unmount()
    enter()
    h.setVisibility('visible')
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(h.intersections.every(({ elements }) => elements.size === 0)).toBe(true)
  })
  it('invalidates a cleared visibility callback and removes listeners on policy off and unmount', async () => {
    const add = vi.spyOn(document, 'addEventListener')
    const remove = vi.spyOn(document, 'removeEventListener')
    h = await mountRequestHarness({ visible: false })
    await h.flush()
    const old = add.mock.calls.find(([type]) => type === 'visibilitychange')![1] as EventListener
    h.request.clearPendingAdRequest()
    h.setVisibility('visible')
    old(new Event('visibilitychange'))
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setVisibility('hidden')
    h.request.reevaluate()
    await h.flush()
    h.setAllowed(false)
    await h.flush()
    expect(remove.mock.calls.filter(([type]) => type === 'visibilitychange')).toHaveLength(2)
    h.setAllowed(true)
    await h.flush()
    h.unmount()
    h.setVisibility('visible')
    old(new Event('visibilitychange'))
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    expect(remove.mock.calls.filter(([type]) => type === 'visibilitychange')).toHaveLength(3)
  })
  it('does not retry a failed SDK when document visibility or width changes', async () => {
    const plugin = await mountPluginHarness()
    try {
      await plugin.nuxtReady()
      const script = document.querySelector<HTMLScriptElement>('script[src*="adsbygoogle.js"]')!
      script.dispatchEvent(new Event('error'))
      plugin.setVisibility('hidden')
      plugin.setVisibility('visible')
      plugin.triggerResize()
      window.dispatchEvent(new Event('resize'))
      await plugin.flush()
      expect(useAdSenseRuntime().loader.value).toEqual({ phase: 'error', attempts: 1 })
      expect(document.querySelectorAll('script[src*="adsbygoogle.js"]')).toHaveLength(1)
      expect(document.querySelector('script[src*="adsbygoogle.js"]')).toBe(script)
    } finally {
      plugin.dispose()
    }
  })
  it('waits for ready and positive width, then requests the element once', async () => {
    h = await mountRequestHarness({ width: 0, ready: false })
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setReady(true)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.setWidth(353)
    h.triggerResize()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.request.attempted.value).toBe(true)
    expect(h.request.outcome.value).toBe('returned')
    h.triggerResize()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('requires policy, connected DOM and a visible ins', async () => {
    h = await mountRequestHarness({ allowed: false })
    await h.flush()
    h.element.value!.style.display = 'none'
    h.setAllowed(true)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.element.value!.style.display = 'block'
    h.host.remove()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    document.body.appendChild(h.host)
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it.each([NaN, undefined, -1])('does not request an invalid width (%s)', async (width) => {
    h = await mountRequestHarness({ width: 0 })
    h.setWidth(width as number)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
  })
  it('deduplicates wait events and handles synchronous reentry and throws', async () => {
    h = await mountRequestHarness({ ready: false })
    await h.flush()
    h.request.reevaluate()
    h.request.reevaluate()
    await h.flush()
    expect(h.events.mock.calls.filter(([kind]) => kind === 'waiting-sdk')).toHaveLength(1)
    h.push.mockImplementation(() => {
      h!.request.reevaluate()
      h!.triggerResize()
      throw new TypeError('private details')
    })
    h.setReady(true)
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.request.outcome.value).toBe('error')
    expect(h.events).toHaveBeenCalledWith('push-error', 'type-error')
    expect(h.observers.every(({ elements }) => elements.size === 0)).toBe(true)
    expect(h.intersections.every(({ elements }) => elements.size === 0)).toBe(true)
    h.request.clearPendingAdRequest()
    h.request.reevaluate()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    h.replaceElement()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(2)
  })
  it('uses window resize when ResizeObserver is unavailable', async () => {
    h = await mountRequestHarness({ width: 0, resizeObserver: false })
    await h.flush()
    h.setWidth(353)
    window.dispatchEvent(new Event('resize'))
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
  })
  it('ignores stale observer callbacks and SDK readiness after unmount', async () => {
    h = await mountRequestHarness({ width: 0 })
    await h.flush()
    const old = h.observers[0]
    h.replaceElement()
    await h.flush()
    h.setWidth(353)
    old.callback([], {} as ResizeObserver)
    await h.flush()
    expect(h.push).not.toHaveBeenCalled()
    h.triggerResize()
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    h.setReady(false)
    h.replaceElement()
    await h.flush()
    h.unmount()
    h.setReady(true)
    await h.flush()
    expect(h.push).toHaveBeenCalledTimes(1)
    expect(h.observers.every((observer) => observer.elements.size === 0)).toBe(true)
  })
})
